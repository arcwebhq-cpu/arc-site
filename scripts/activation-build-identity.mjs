export const ACTIVATION_BUILD_IDENTITY_SCHEMA = 'arc-activation-build-identity-v1';
export const ACTIVATION_BUILD_IDENTITY_VERSION = 1;
export const ACTIVATION_DEPLOYMENT_SHA_PATTERN = /^[a-f0-9]{40}$/;

export function activationBuildIdentity(commitRef) {
  if (commitRef === undefined || commitRef === '') {
    return Object.freeze({
      schema: ACTIVATION_BUILD_IDENTITY_SCHEMA,
      version: ACTIVATION_BUILD_IDENTITY_VERSION,
      deployment_sha: null,
    });
  }
  if (!ACTIVATION_DEPLOYMENT_SHA_PATTERN.test(commitRef)) {
    throw new Error('COMMIT_REF must be exactly 40 lowercase hexadecimal characters when present.');
  }
  return Object.freeze({
    schema: ACTIVATION_BUILD_IDENTITY_SCHEMA,
    version: ACTIVATION_BUILD_IDENTITY_VERSION,
    deployment_sha: commitRef,
  });
}

export function activationBuildIdentityModule(commitRef) {
  const identity = activationBuildIdentity(commitRef);
  return `// Generated by scripts/build-site.mjs from Netlify's build-scoped COMMIT_REF.\n// This non-secret value is bundled into the same deploy's Functions.\nexport const ACTIVATION_BUILD_IDENTITY = Object.freeze(${JSON.stringify(identity, null, 2)});\n`;
}
